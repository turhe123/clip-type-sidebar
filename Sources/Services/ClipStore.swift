import AppKit
import UniformTypeIdentifiers

/// Polls the general pasteboard, classifies new content, and owns the persisted history.
@MainActor
final class ClipStore: ObservableObject {
    static let shared = ClipStore()

    @Published private(set) var items: [ClipItem] = []
    @Published var paused = false

    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private var asleep = false
    private let thumbCache = NSCache<NSString, NSImage>()
    private var iconCache: [String: NSImage] = [:]

    private let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]
    private let hexRegex = try? NSRegularExpression(pattern: "^#?([0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$")
    private let linkDetector = try? NSDataDetector(types: NSTextCheckingResult.CheckingType.link.rawValue)

    private let folder: URL = {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first
            ?? URL(fileURLWithPath: NSTemporaryDirectory())
        return base.appendingPathComponent("ClipTypeSidebar", isDirectory: true)
    }()
    private var imagesFolder: URL { folder.appendingPathComponent("images", isDirectory: true) }
    private var historyURL: URL { folder.appendingPathComponent("history.json") }

    private init() {
        try? FileManager.default.createDirectory(at: imagesFolder, withIntermediateDirectories: true)
        load()
        prune()
        let ws = NSWorkspace.shared.notificationCenter
        ws.addObserver(forName: NSWorkspace.willSleepNotification, object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { self?.asleep = true; self?.timer?.invalidate() }
        }
        ws.addObserver(forName: NSWorkspace.didWakeNotification, object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { self?.asleep = false; self?.start() }
        }
    }

    // MARK: Polling

    func start() {
        timer?.invalidate()
        lastChange = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard !asleep, pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard !paused else { return }
        let types = pb.types ?? []
        if types.contains(where: { skipTypes.contains($0.rawValue) }) { return }
        let front = NSWorkspace.shared.frontmostApplication
        if let bid = front?.bundleIdentifier, ignoredApps.contains(bid) { return }
        guard var item = classify(pb, types: types) else { return }
        item.sourceBundleID = front?.bundleIdentifier
        item.sourceName = front?.localizedName
        insert(item)
    }

    private var ignoredApps: Set<String> {
        let raw = UserDefaults.standard.string(forKey: "ignoredApps") ?? ""
        return Set(raw.split(whereSeparator: \.isNewline).map { $0.trimmingCharacters(in: .whitespaces) })
    }

    private func classify(_ pb: NSPasteboard, types: [NSPasteboard.PasteboardType]) -> ClipItem? {
        let opts: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: opts) as? [URL], !urls.isEmpty {
            return ClipItem(kind: .files, text: urls.map(\.path).joined(separator: "\n"), filePaths: urls.map(\.path))
        }
        let hasImage = types.contains { UTType($0.rawValue)?.conforms(to: .image) == true }
        let string = pb.string(forType: .string)
        if hasImage, string == nil, let image = NSImage(pasteboard: pb),
           let png = Self.pngData(from: image, maxPixel: 2560) {
            let name = UUID().uuidString + ".png"
            do { try png.write(to: imagesFolder.appendingPathComponent(name)) } catch { return nil }
            return ClipItem(kind: .image, imageFile: name)
        }
        guard let text = string, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        let range = NSRange(trimmed.startIndex..., in: trimmed)
        if hexRegex?.firstMatch(in: trimmed, range: range) != nil {
            return ClipItem(kind: .color, text: trimmed.hasPrefix("#") ? trimmed : "#" + trimmed)
        }
        if let match = linkDetector?.firstMatch(in: trimmed, range: range), match.range == range {
            return ClipItem(kind: .link, text: trimmed)
        }
        if types.contains(.rtf), let rtf = pb.data(forType: .rtf), rtf.count < 512_000 {
            return ClipItem(kind: .richText, text: text, rtf: rtf)
        }
        return ClipItem(kind: .text, text: text)
    }

    private func insert(_ item: ClipItem) {
        var item = item
        if item.kind != .image, let idx = items.firstIndex(where: { $0.kind == item.kind && $0.text == item.text }) {
            item.pinned = items[idx].pinned
            items.remove(at: idx)
        }
        items.insert(item, at: 0)
        prune()
    }

    // MARK: Mutations

    func remove(_ id: UUID) { items.removeAll { $0.id == id }; prune() }
    func togglePin(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        items[i].pinned.toggle(); save()
    }
    func clear() { items.removeAll { !$0.pinned }; prune() }

    func transform(_ id: UUID, with t: TextTransform) {
        guard let i = items.firstIndex(where: { $0.id == id }), let text = items[i].text else { return }
        items[i].text = t.apply(text)
        items[i].rtf = nil
        if items[i].kind == .richText { items[i].kind = .text }
        save()
    }

    /// Writes an item to the pasteboard and remembers the change count so it is not re-recorded.
    func copyToPasteboard(_ item: ClipItem, plain: Bool) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .image:
            if let image = image(for: item) { pb.writeObjects([image]) }
        case .files where !plain:
            let urls = (item.filePaths ?? []).map { URL(fileURLWithPath: $0) as NSURL }
            pb.writeObjects(urls)
        case .richText where !plain:
            if let rtf = item.rtf { pb.setData(rtf, forType: .rtf) }
            pb.setString(item.text ?? "", forType: .string)
        default:
            pb.setString(item.text ?? "", forType: .string)
        }
        lastChange = pb.changeCount
        if !item.pinned, let i = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: i)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
    }

    /// Applies the history size and age limits, then deletes orphaned image files.
    func prune() {
        let defaults = UserDefaults.standard
        let limit = min(max(defaults.integer(forKey: "historySize"), 10), 500)
        let days = defaults.integer(forKey: "daysToKeep")
        if days > 0 {
            let cutoff = Date().addingTimeInterval(-Double(days) * 86_400)
            items.removeAll { !$0.pinned && $0.date < cutoff }
        }
        var unpinned = 0
        items = items.filter { item in
            if item.pinned { return true }
            unpinned += 1
            return unpinned <= limit
        }
        let referenced = Set(items.compactMap(\.imageFile))
        let files = (try? FileManager.default.contentsOfDirectory(atPath: imagesFolder.path)) ?? []
        for file in files where !referenced.contains(file) {
            try? FileManager.default.removeItem(at: imagesFolder.appendingPathComponent(file))
            thumbCache.removeObject(forKey: file as NSString)
        }
        save()
    }

    // MARK: Persistence

    private func load() {
        guard let data = try? Data(contentsOf: historyURL) else { return }
        items = (try? JSONDecoder().decode([ClipItem].self, from: data)) ?? []
    }

    private func save() {
        do {
            let data = try JSONEncoder().encode(items)
            try data.write(to: historyURL, options: .atomic)
        } catch {
            NSLog("ClipTypeSidebar: failed to save history: \(error.localizedDescription)")
        }
    }

    // MARK: Images & icons

    func image(for item: ClipItem) -> NSImage? {
        guard let name = item.imageFile else { return nil }
        return NSImage(contentsOf: imagesFolder.appendingPathComponent(name))
    }

    func thumbnail(for item: ClipItem) -> NSImage? {
        guard let name = item.imageFile else { return nil }
        if let cached = thumbCache.object(forKey: name as NSString) { return cached }
        guard let full = image(for: item), let data = Self.pngData(from: full, maxPixel: 160),
              let thumb = NSImage(data: data) else { return nil }
        thumbCache.setObject(thumb, forKey: name as NSString)
        return thumb
    }

    func appIcon(_ bundleID: String?) -> NSImage? {
        guard let bundleID else { return nil }
        if let icon = iconCache[bundleID] { return icon }
        guard let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID) else { return nil }
        let icon = NSWorkspace.shared.icon(forFile: url.path)
        iconCache[bundleID] = icon
        return icon
    }

    /// Re-encodes an image as PNG, downscaling so its longest side is at most `maxPixel`.
    static func pngData(from image: NSImage, maxPixel: CGFloat) -> Data? {
        guard let cg = image.cgImage(forProposedRect: nil, context: nil, hints: nil) else { return nil }
        let w = CGFloat(cg.width), h = CGFloat(cg.height)
        let scale = min(1, maxPixel / max(w, h, 1))
        let nw = max(1, Int(w * scale)), nh = max(1, Int(h * scale))
        let space = CGColorSpace(name: CGColorSpace.sRGB) ?? CGColorSpaceCreateDeviceRGB()
        guard let ctx = CGContext(data: nil, width: nw, height: nh, bitsPerComponent: 8, bytesPerRow: 0,
                                  space: space, bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue) else { return nil }
        ctx.interpolationQuality = .high
        ctx.draw(cg, in: CGRect(x: 0, y: 0, width: nw, height: nh))
        guard let out = ctx.makeImage() else { return nil }
        return NSBitmapImageRep(cgImage: out).representation(using: .png, properties: [:])
    }
}
